# Turns data/*.json (extracted from the games) into small scripts the pages load.
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
for name, var in (('ores', 'ORES'), ('rng', 'RNG')):
    d = json.load(open(os.path.join(ROOT, 'data', name + '.json'), encoding='utf-8'))
    js = '// Generated by tools/build_data.py from data/%s.json, which is extracted from the game source.\nwindow.%s = %s;\n' % (name, var, json.dumps(d, ensure_ascii=False, separators=(',', ':')))
    open(os.path.join(ROOT, 'docs', 'assets', 'js', 'data-' + name + '.js'), 'w', encoding='utf-8').write(js)
    print(name, len(js))
